    def test_task_run_daily_mode_files_endpoint_finds_subdirectory_files(self, client, tmp_path):
        """task_run daily mode generates files in output/run_id/YYYY-MM-DD/."""
        h = run_history.RunHistory()
        rid = h.create_run(
            "Test Task Daily", "task_run",
            {"task_config": "config/tasks_test.yaml", "daily": True}
        )
        
        # Simulate execution output (daily mode - date subdirectory)
        output_dir = tmp_path / rid
        output_dir.mkdir()
        
        date_dir = output_dir / "2026-05-05"
        date_dir.mkdir()
        
        md_file = date_dir / "Daily_Report.md"
        md_file.write_text("# Daily Report 2026-05-05")
        
        json_file = date_dir / "Combined_Results.json"
        json_file.write_text(json.dumps([{"code": "NVDA.US"}]))
        
        task_json = date_dir / "task1.json"
        task_json.write_text(json.dumps({"signals": []}))
        
        # Update run status
        # Note: report_path contains date, output_path does not
        h.update_status(
            rid, "completed",
            output_path=str(output_dir),  # base output, no date
            report_path=str(md_file),      # contains date
            signal_count=1
        )
        
        # Test files endpoint - should find files in subdirectory
        files_resp = client.get(f"/api/runs/{rid}/files")
        assert files_resp.status_code == 200
        
        files = files_resp.json()["files"]
        file_names = {f["name"] for f in files}
        
        # Should find all files in date subdirectory
        assert "Daily_Report.md" in file_names
        assert "Combined_Results.json" in file_names
        assert "task1.json" in file_names
        
        # Verify paths contain date directory
        for f in files:
            assert "2026-05-05" in f["path"]
            assert Path(f["path"]).exists()