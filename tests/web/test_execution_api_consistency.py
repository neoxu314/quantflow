class TestFilesEndpointExecutionConsistency:
    """Verify files endpoint finds files generated by execution."""
    
    def test_stock_scan_files_endpoint_finds_indicator_json(self, client, tmp_path):
        """stock_scan execution generates indicators.json in output/run_id/."""
        from quantflow.web.engine.run_engine import RunEngine
        from quantflow.web.engine.run_history import RunHistory
        
        # Setup
        h = RunHistory()
        rid = h.create_run("Test Scan", "stock_scan", {"code": "NVDA.US"})
        
        # Simulate execution output
        output_dir = tmp_path / rid
        output_dir.mkdir()
        indicator_file = output_dir / "NVDA.US_indicators.json"
        indicator_data = [{"date": "2026-05-05", "kdj_k": 50.0}]
        indicator_file.write_text(json.dumps(indicator_data))
        
        # Update run status (simulating execution completion)
        h.update_status(
            rid, "completed",
            output_path=str(output_dir),
            report_path=str(indicator_file),
            signal_count=1
        )
        
        # Test files endpoint
        files_resp = client.get(f"/api/runs/{rid}/files")
        assert files_resp.status_code == 200
        
        files = files_resp.json()["files"]
        assert len(files) >= 1
        
        # Verify file details
        file_names = {f["name"] for f in files}
        assert "NVDA.US_indicators.json" in file_names
        
        # Verify path is correct
        json_files = [f for f in files if f["name"] == "NVDA.US_indicators.json"]
        assert len(json_files) == 1
        assert Path(json_files[0]["path"]).exists()
        assert json_files[0]["type"] == "json"
        
